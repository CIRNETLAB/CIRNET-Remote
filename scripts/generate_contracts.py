"""Generate/check all committed structural boundary artifacts transactionally.

Generate to a workspace-local temporary tree, compare without mutation in check
mode, and replace outputs only after every generator has succeeded. Output
normalization is UTF-8/LF with no timestamps or machine-specific source paths.
"""
import argparse
import json
from pathlib import Path
import shutil
import subprocess
import sys
from tempfile import TemporaryDirectory
import uuid
import pprint

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from contracts.registry import check_manifest, entries, load_schema, schema_bundle


def capture_layout_outputs():
    """One checked binary-layout resource emits constants with all other contracts."""
    from contracts.registry import validate_contract
    layout=json.loads((ROOT/'contracts/capture/layout.json').read_text(encoding='utf-8'))
    validate_contract('NCAPLayout',layout)
    return {
        'apps/web/src/contracts/generated/captureLayout.ts': '// Generated by scripts/generate_contracts.py from contracts/capture/layout.json.\nexport const captureLayout = '+json.dumps(layout,indent=2)+' as const\n',
        'contracts/boundary/capture_layout.py': '# Generated by scripts/generate_contracts.py from contracts/capture/layout.json.\nCAPTURE_LAYOUT = '+pprint.pformat(layout,sort_dicts=False,width=100)+'\n',
    }


def publish_artifacts(artifacts, output_root):
    """Publish the set, rolling back changed files on an ordinary I/O failure."""
    output_root=Path(output_root).resolve()
    identity=uuid.uuid4().hex
    pending={}
    originals={}
    replaced=[]
    try:
        for relative, source in artifacts.items():
            target=(output_root/relative).resolve()
            if not target.is_relative_to(output_root):
                raise ValueError(f'Artifact escapes output root: {relative}')
            target.parent.mkdir(parents=True,exist_ok=True)
            originals[target]=target.read_bytes() if target.exists() else None
            candidate=target.with_name(target.name+'.'+identity+'.new')
            pending[target]=candidate
            shutil.copyfile(source,candidate)
        for target,candidate in pending.items():
            candidate.replace(target)
            replaced.append(target)
    except Exception:
        for target in reversed(replaced):
            original=originals[target]
            if original is None:
                target.unlink()
            else:
                rollback=target.with_name(target.name+'.'+identity+'.rollback')
                rollback.write_bytes(original)
                rollback.replace(target)
        raise
    finally:
        for candidate in pending.values():
            if candidate.exists():
                candidate.unlink()


def generate(*, check=False, output_root=ROOT):
    check_manifest()
    workspace = ROOT / '.build'
    workspace.mkdir(exist_ok=True)
    with TemporaryDirectory(prefix='contracts-', dir=workspace) as temporary:
        stage = Path(temporary)
        bundle = stage / 'public.json'
        bundle.write_text(json.dumps({profile:schema_bundle(public_only=True, profile=profile)
                                     for profile in ('structural','editor','transport')}, indent=2)+'\n', encoding='utf-8')
        generated = stage / 'apps/web/src/contracts/generated'
        subprocess.run(['node', str(ROOT/'apps/web/scripts/generate-contracts.mjs'), str(bundle), str(generated)],
                       cwd=ROOT/'apps/web', check=True)
        python = stage / 'contracts/boundary/models.py'
        python.parent.mkdir(parents=True)
        subprocess.run([sys.executable, str(ROOT/'scripts/generate_python_contracts.py'), '--output', str(python)], cwd=ROOT, check=True)
        subprocess.run([sys.executable,str(ROOT/'scripts/export_openapi.py'),
                        '--models',str(python),'--output',str(stage/'contracts/api/openapi.json'),
                        '--operations',str(generated/'operations.ts')],cwd=ROOT,check=True)
        lab_entries = [entry for entry in entries() if entry['path']=='contracts/physical-lab/lab.schema.json' and entry['visibility']=='public']
        lab = load_schema('https://netcircuit.local/contracts/physical-lab/1.0/lab.schema.json')
        lab['$defs'] = {entry['id']:lab['$defs'][entry['id']] for entry in lab_entries}
        outputs = {
            'apps/web/src/types/lab.ts': '// Generated by scripts/generate_contracts.py; edit canonical contracts.\nexport type { '+', '.join(entry['id'] for entry in lab_entries)+" } from '../contracts/generated/dto'\n",
            'apps/web/src/data/labContracts.json': json.dumps(lab, indent=2)+'\n',
        }
        outputs.update(capture_layout_outputs())
        for path, text in outputs.items():
            target = stage / path
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_text(text, encoding='utf-8', newline='\n')
        bundle.unlink()
        artifacts = {path.relative_to(stage):path for path in stage.rglob('*') if path.is_file()
                     and '__pycache__' not in path.parts and path.suffix not in ('.pyc','.pyo')}
        stale = [str(path) for path, source in artifacts.items() if not (output_root/path).exists() or (output_root/path).read_bytes()!=source.read_bytes()]
        if check:
            if stale:
                raise SystemExit('Stale contract artifacts:\n'+'\n'.join(stale))
        else:
            publish_artifacts(artifacts,output_root)


if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    parser.add_argument('--output-root', type=Path, default=ROOT)
    options = parser.parse_args()
    generate(check=options.check, output_root=options.output_root.resolve())
