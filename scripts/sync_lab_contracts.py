"""Generate browser schema snapshot/types from canonical Lab-First definitions."""
import argparse
import json
from pathlib import Path

ROOT=Path(__file__).resolve().parents[1]


def ts(schema):
    if '$ref' in schema: return schema['$ref'].rsplit('/',1)[-1]
    if 'anyOf' in schema: return ' | '.join(ts(s) for s in schema['anyOf'])
    if 'const' in schema: return json.dumps(schema['const'])
    if 'enum' in schema: return ' | '.join(json.dumps(v) for v in schema['enum'])
    kind=schema.get('type')
    if kind=='array': return f'Array<{ts(schema["items"])}>'
    if kind=='object':
        if 'properties' not in schema:
            return f'Record<string, {ts(schema.get("additionalProperties",{}))}>'
        required=schema.get('required',[])
        return '{ '+ '; '.join(f'{key}{"" if key in required else "?"}: {ts(value)}' for key,value in schema['properties'].items())+' }'
    return {'string':'string','integer':'number','number':'number','boolean':'boolean','null':'null'}.get(kind,'unknown')


def generate(check=False):
    schema=json.loads((ROOT/'contracts/physical-lab/lab.schema.json').read_text(encoding='utf-8'))
    outputs={ROOT/'apps/web/src/data/labContracts.json':json.dumps(schema,indent=2)+'\n',
             ROOT/'apps/web/src/types/lab.ts':'// Generated by scripts/sync_lab_contracts.py; edit canonical contracts.\n'+
             '\n'.join(f'export type {name} = {ts(definition)}' for name,definition in schema['$defs'].items())+'\n'}
    for path,value in outputs.items():
        if check:
            if not path.exists() or path.read_text(encoding='utf-8')!=value: raise SystemExit(f'Stale Lab-First snapshot: {path.relative_to(ROOT)}')
        else: path.write_text(value,encoding='utf-8',newline='\n')


if __name__=='__main__':
    parser=argparse.ArgumentParser(); parser.add_argument('--check',action='store_true')
    generate(parser.parse_args().check)
