// JSON Schema is shape authority. This script only orchestrates pinned tools.
import { readFile, writeFile, mkdir } from 'node:fs/promises'
import { resolve } from 'node:path'
import Ajv2020 from 'ajv/dist/2020.js'
import standalone from 'ajv/dist/standalone/index.js'
import { compile } from 'json-schema-to-typescript'
import { build } from 'esbuild'

const [input, output] = process.argv.slice(2)
if (!input || !output) throw new Error('Usage: node generate-contracts.mjs BUNDLE.json OUTPUT')
const profiles = JSON.parse(await readFile(input, 'utf8'))
const schema = profiles.transport
const names = Object.keys(schema.$defs)
await mkdir(output, { recursive: true })
for (const [profile, schema] of Object.entries(profiles)) {
const ajv = new Ajv2020({ strict: true, strictRequired: false, strictTypes: false,
  allErrors: true, coerceTypes: false, useDefaults: false, removeAdditional: false,
  inlineRefs: false, code: { source: true, lines: true, esm: true }, loopRequired: 200 })
ajv.addSchema(schema)
const exports = Object.fromEntries(names.map(name => [name, `${schema.$id}#/$defs/${name}`]))
for (const uri of Object.values(exports)) if (!ajv.getSchema(uri)) throw new Error(`Unresolved export ${uri}`)
const source = standalone.default ? standalone.default(ajv, exports) : standalone(ajv, exports)
// Bundle Ajv's small static helpers as ESM. No runtime Function/eval or Ajv
// compiler is shipped to the browser; browser CSP can disallow dynamic code.
const bundled = await build({ stdin: { contents: source, resolveDir: process.cwd(), sourcefile: 'validators.mjs' },
  bundle: true, platform: 'browser', format: 'esm', write: false, legalComments: 'none', minify: false })
const stem = profile === 'transport' ? 'validators' : `validators.${profile}`
const declarations = `// Generated. DO NOT EDIT.\nimport type { ContractMap } from './dto'\nexport interface ValidationIssue { instancePath: string; keyword: string; message?: string; params: Record<string, unknown> }\nexport interface Validator<T> { (value: unknown): value is T; errors?: ValidationIssue[] | null }\n${names.map(name=>`export const ${name}: Validator<ContractMap['${name}']>`).join('\n')}\n`
await writeFile(resolve(output, `${stem}.js`), '// Generated by pinned Ajv 2020. DO NOT EDIT.\n'+bundled.outputFiles[0].text, 'utf8')
await writeFile(resolve(output, `${stem}.d.ts`), declarations, 'utf8')
}
const dto = await compile({ ...schema, title: 'ContractMap' }, 'ContractMap', { bannerComment: '// Generated from contracts/manifest.json by scripts/generate_contracts.py. DO NOT EDIT.',
  unknownAny: true, unreachableDefinitions: true, ignoreMinAndMaxItems: true,
  style: { singleQuote: true, semi: false, tabWidth: 2 }, additionalProperties: true })
await writeFile(resolve(output, 'dto.ts'), dto.replaceAll('\r\n','\n'), 'utf8')
